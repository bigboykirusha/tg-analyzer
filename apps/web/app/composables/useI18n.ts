function interpolate(template: string, params?: Record<string, string | number>) {
  if (!params) {
    return template
  }

  return Object.entries(params).reduce((value, [key, item]) => value.replaceAll(`{${key}}`, String(item)), template)
}

export function useI18n() {
  const locale = useState<Locale>('tg-analyzer-locale', () => 'ru')

  onMounted(() => {
    const saved = localStorage.getItem(LOCALE_KEY)
    if (saved === 'ru' || saved === 'en') {
      locale.value = saved
    }
  })

  const intlLocale = computed(() => locale.value === 'ru' ? 'ru-RU' : 'en-US')

  function setLocale(nextLocale: Locale) {
    locale.value = nextLocale
    if (import.meta.client) {
      localStorage.setItem(LOCALE_KEY, nextLocale)
    }
  }

  function t(key: string, params?: Record<string, string | number>) {
    return interpolate(messages[locale.value][key] ?? messages.en[key] ?? key, params)
  }

  function formatNumber(value: number) {
    return new Intl.NumberFormat(intlLocale.value).format(value)
  }

  function formatDate(value: string | Date | null | undefined, options?: Intl.DateTimeFormatOptions) {
    if (!value) {
      return t('common.na')
    }
    const date = value instanceof Date ? value : new Date(value)
    if (Number.isNaN(date.getTime()) || date.getUTCFullYear() < 2000) {
      return t('common.na')
    }
    return new Intl.DateTimeFormat(intlLocale.value, options ?? { dateStyle: 'medium', timeStyle: 'short' }).format(date)
  }

  function formatRelative(value: string | null | undefined) {
    if (!value) {
      return t('common.unknown')
    }
    const date = new Date(value)
    if (Number.isNaN(date.getTime()) || date.getUTCFullYear() < 2000) {
      return t('common.unknown')
    }
    const diffMs = Date.now() - date.getTime()
    const diffHours = Math.max(0, Math.floor(diffMs / (60 * 60 * 1000)))
    if (diffHours < 1) {
      return t('common.justNow')
    }
    if (diffHours < 24) {
      return t('common.hoursAgo', { value: diffHours })
    }
    return t('common.daysAgo', { value: Math.floor(diffHours / 24) })
  }

  return {
    locale,
    intlLocale,
    setLocale,
    t,
    formatNumber,
    formatDate,
    formatRelative,
  }
}
